"""Writes worklist-v0/hpacs-lite/dicom-dictionary.js: the DICOM data dictionary (PS3.6) the viewer's Corner
Information window offers for choosing on-image items.

Source: the PS3.6 data dictionary as packaged by pydicom (pinned below). Kept: public elements with a keyword whose
value can be shown as text. Left out: value representations that are not text (SQ, OB, OW, OF, OD, OL, OV, UN),
command, file meta and directory groups (0000, 0002, 0004), item delimiters (FFFE) and repeating groups (xx).
Retired elements stay, marked, since older images still carry them.

    python -B scripts/build-dicom-dictionary.py           # write
    python -B scripts/build-dicom-dictionary.py --check   # fail when the file differs from what would be written
"""
import json
import sys
from pathlib import Path

import pydicom
from pydicom._dicom_dict import DicomDictionary

PYDICOM = '2.4.4'
OUT = Path(__file__).resolve().parents[1] / 'worklist-v0' / 'hpacs-lite' / 'dicom-dictionary.js'
NOT_TEXT = {'SQ', 'OB', 'OW', 'OF', 'OD', 'OL', 'OV', 'UN'}
SKIP_GROUPS = {0x0000, 0x0002, 0x0004, 0xFFFE}


def entries():
    rows = []
    for tag in sorted(DicomDictionary):
        vr, _vm, name, retired, keyword = DicomDictionary[tag]
        group = tag >> 16
        if group in SKIP_GROUPS or not keyword or not name:
            continue
        vrs = set(part.strip() for part in vr.split(' or '))
        if vrs & NOT_TEXT == vrs or 'SQ' in vrs:
            continue
        row = ['%08X' % tag, keyword, name, '/'.join(sorted(vrs))]
        if retired:
            row.append(1)
        rows.append(row)
    return rows


def render():
    rows = entries()
    body = ',\n'.join(json.dumps(row, ensure_ascii=False, separators=(',', ':')) for row in rows)
    return ('// The DICOM data dictionary (DICOM PS3.6) for choosing on-image corner items in the viewer.\n'
            '// Generated by scripts/build-dicom-dictionary.py from the dictionary packaged with pydicom ' + PYDICOM + '; do not edit.\n'
            '// Each entry: [tag (8 hex digits), keyword, name, VR, retired (1 when retired)].\n'
            '(function (root) {\n'
            "  'use strict';\n"
            '  root.KinDicomDictionary = Object.freeze({ source: ' + json.dumps('DICOM PS3.6 (pydicom ' + PYDICOM + ')') + ', entries: [\n'
            + body + '\n  ] });\n'
            "})(typeof window === 'undefined' ? globalThis : window);\n")


def main():
    if pydicom.__version__ != PYDICOM:
        sys.exit('pydicom %s is required (found %s)' % (PYDICOM, pydicom.__version__))
    text = render()
    if '--check' in sys.argv[1:]:
        if OUT.read_text(encoding='utf-8') != text:
            sys.exit(str(OUT) + ' differs from the generated dictionary; run scripts/build-dicom-dictionary.py')
        print('dicom-dictionary.js matches (%d entries)' % len(entries()))
        return
    OUT.write_text(text, encoding='utf-8', newline='\n')
    print('wrote %s (%d entries, %d bytes)' % (OUT, len(entries()), len(text.encode('utf-8'))))


if __name__ == '__main__':
    main()
